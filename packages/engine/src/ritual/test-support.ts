export function stackItem(
  id: string,
  itemKey: string | null,
  over: Partial<StackItemLike> = {},
): StackItemLike {
  return {
    id,
    itemKey,
    monthlyCost: over.monthlyCost ?? (itemKey ? catalogView.item(itemKey)?.costMonthUsd ?? 10 : 0),
    answers: {},
    status: 'listed',
    notes: [],
    ...over,
  };
}

