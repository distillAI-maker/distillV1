async function main() {
  if (args[0] === '--worker') {
    const { jobs, seed } = JSON.parse(args[1]!) as { jobs: Job[]; seed: number };
    const cells: CellResult[] = [];
    for (const job of jobs) {
      const result = simulateCell(job.scenario, job.effect, job.trials, seed);
      cells.push(result);
      process.send?.({
        progress: `${job.scenario.id}: effect ${job.effect}, ${job.trials} trials`,
      });
    }
    process.send?.({ cells });
    process.disconnect?.();
    return;
  }
  if (
    args.some(
      (arg) =>
        !/^--(quick|check)$|^--(trials|null-trials|coverage-trials|workers|seed)=\d+$/.test(arg),
    )
  )
    throw new Error('Unknown argument');
  if (args.includes('--check')) {
    const report = JSON.parse(await readFile('data/power-results.json', 'utf8')) as {
      metadata: { sourceHash: string };
    };
    if (report.metadata.sourceHash !== (await sourceHash()))
      throw new Error('Power report is stale; regenerate after changing the model or engine');
    console.log('Power report source provenance is current');
    return;
  }
  const quick = args.includes('--quick'),
    trials = option('trials', quick ? 20 : 500),
    nullTrials = option('null-trials', quick ? 40 : 2000),
    coverageTrials = option('coverage-trials', quick ? 10 : 250);
  const seed = option('seed', 20261003);
  assertSeed(seed);
  const workers = option('workers', 4);
  if (workers > 8) throw new Error('Use at most eight workers');
  const startingHash = await sourceHash();
  const jobs: Job[] = [];
  for (const scenario of powerScenarios)
    for (const effect of effectGrid)
      jobs.push({ scenario, effect, trials: effect === 0 ? nullTrials : trials });
  for (const scenario of [...sensitivityScenarios, ...metricScenarios])
    for (const effect of [0, 0.8, 1.2, -1.2])
      jobs.push({ scenario, effect, trials: effect === 0 ? nullTrials : trials });
  for (const scenario of coverageScenarios)
    for (const effect of [0, 0.8, 1.2]) jobs.push({ scenario, effect, trials: coverageTrials });
  const partitions: Job[][] = Array.from({ length: workers }, () => []);
  const loads = Array<number>(workers).fill(0);
  const weight = (job: Job) =>
    job.trials * (job.scenario.withInterval ? 5 : 1) * (job.scenario.schedule.totalDays ?? 14);
  for (const job of [...jobs].sort((a, b) => weight(b) - weight(a))) {
    const index = loads.indexOf(Math.min(...loads));
    partitions[index]!.push(job);
    loads[index] = loads[index]! + weight(job);
  }
  const results = await Promise.all(
    partitions.map(
      (partition) =>
        new Promise<CellResult[]>((accept, reject) => {
          const child = fork(
            fileURLToPath(import.meta.url),
            ['--worker', JSON.stringify({ jobs: partition, seed })],
            { stdio: ['ignore', 'inherit', 'inherit', 'ipc'] },
          );
          let received = false;
          child.on('message', (message: { progress?: string; cells?: CellResult[] }) => {
            if (message.progress) console.log(message.progress);
            if (message.cells) {
              received = true;
              accept(message.cells);
            }
          });
          child.on('error', reject);
          child.on('exit', (code) => {
            if (code !== 0 || !received) reject(new Error(`Simulation worker exited ${code}`));
          });
        }),
    ),
  );
  const cells = results
    .flat()
    .sort((a, b) => a.scenario.id.localeCompare(b.scenario.id) || a.effect - b.effect);
  if (startingHash !== (await sourceHash()))
    throw new Error('Simulation sources changed during the run; regenerate from a stable tree');
  const metadata = {
    version: 1,
    seed,
    trials,
    nullTrials,
    coverageTrials,
    bootstrapIterations: 1000,
    attemptedTrials: cells.reduce((sum, cell) => sum + cell.trials, 0),
    sourceHash: await sourceHash(),
    generator: 'stationary AR(1), independent streams, bounded metrics, lognormal HRV',
    metricModels,
    inference:
      'exact constrained block randomization; dual tails at 0.025 each unless explicitly legacy',
    quick,
  };
  await mkdir(quick ? '.local' : 'data', { recursive: true });
  await writeFile(
    resolve(quick ? '.local/power-quick.json' : 'data/power-results.json'),
    JSON.stringify({ metadata, cells }, null, 2) + '\n',
  );
  if (!quick) await writeFile('docs/POWER.md', render(cells, metadata));
  console.log(
    `Completed ${metadata.attemptedTrials} attempts. ${quick ? 'Quick results only; not validation.' : 'Wrote data/power-results.json and docs/POWER.md.'}`,
  );
}
await main();
