type Job = { scenario: Scenario; effect: number; trials: number };
export async function sourceHash() {
  const paths: string[] = ['data/catalog.json'];
  async function walk(path: string) {
    for (const entry of await readdir(path, { withFileTypes: true })) {
      const child = `${path}/${entry.name}`;
      if (entry.isDirectory()) await walk(child);
      else if (
        entry.name.endsWith('.ts') &&
        !entry.name.endsWith('.test.ts') &&
        !['index.ts', 'demo.ts', 'local.ts', 'guidance.ts'].includes(entry.name)
      )
        paths.push(child);
    }
  }
  await walk('packages/sim/src');
  await walk('packages/engine/src');
  paths.push('scripts/sim-power.ts');
  const hash = createHash('sha256');
  for (const path of paths.sort()) hash.update(path).update(await readFile(path));
  return hash.digest('hex');
}
const args = process.argv.slice(2);
function option(name: string, fallback: number) {
  const values = args.filter((arg) => arg.startsWith(`--${name}=`));
  if (values.length > 1) throw new Error(`Duplicate ${name}`);
  const value = values[0] ? Number(values[0].split('=')[1]) : fallback;
  if (
    !Number.isInteger(value) ||
    value < 0 ||
    value > (name === 'seed' ? 0xffffffff : 100000) ||
    (name !== 'seed' && value === 0)
  )
    throw new Error(`Invalid ${name}`);
  return value;
}
function percent(rate: CellResult['decisive']) {
  if (rate.value === null || !rate.interval95) return '—';
  return `${(rate.value * 100).toFixed(1)}% [${(rate.interval95[0] * 100).toFixed(1)}, ${(rate.interval95[1] * 100).toFixed(1)}]`;
}
